    internal static string ToString(Message message)
    {
        static string Parenthesize(string? value) => value is null ? string.Empty : $" ({value})";
        uint id = unchecked((uint)message.Msg);
        string parentNotification = id == 0x0210
            ? Parenthesize(GetName(unchecked((uint)((nuint)message.WParam & 0xffff))))
            : string.Empty;
        return $"msg=0x{id:x}{Parenthesize(GetName(id))} hwnd=0x{(long)message.HWnd:x} wparam=0x{message.WParam:x} lparam=0x{message.LParam:x}{parentNotification} result=0x{message.Result:x}";
    }

    private static string? GetName(uint message)
    {
        string? name = KnownName(message);
        if (name is null && (message & 0x2000) == 0x2000)
        {
            name = $"WM_REFLECT + {GetName(message - 0x2000) ?? "???"}";
        }
        return name;
    }

